CREATE OR REPLACE FUNCTION public.normalize_lead_company_name(p_name text)
RETURNS text
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
SET search_path = pg_catalog
AS $$
  SELECT nullif(regexp_replace(lower(btrim(coalesce(p_name, ''))), '[[:space:]]+', ' ', 'g'), '');
$$;

CREATE OR REPLACE FUNCTION public.normalize_lead_company_domain(p_website text)
RETURNS text
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
SET search_path = pg_catalog
AS $$
  SELECT nullif(
    regexp_replace(
      regexp_replace(
        regexp_replace(
          split_part(
            regexp_replace(btrim(coalesce(p_website, '')), '^https?://', '', 'i'),
            '/', 1
          ),
          '[?#].*$', ''
        ),
        '^www[.]', '', 'i'
      ),
      ':[0-9]+$', ''
    ),
    ''
  );
$$;

