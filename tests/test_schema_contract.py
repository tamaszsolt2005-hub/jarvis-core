"""Regression checks for the deployable Supabase schema."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def test_schema_migrations_are_real_sql_lines_not_escaped_text():
    schema = (ROOT / "supabase" / "schema.sql").read_text(encoding="utf-8")
    assert "\\n" not in schema
    assert "alter table public.leads add column if not exists website text;" in schema
    migration = (ROOT / "supabase" / "migrations" / "20261117090000_add_leads_website.sql").read_text(encoding="utf-8")
    assert "add column if not exists website text" in migration
    assert "alter table public.logs add column if not exists level text not null default" in schema
    logs_migration = (ROOT / "supabase" / "migrations" / "20261117100000_add_logs_level.sql").read_text(encoding="utf-8")
    assert "add column if not exists level text not null default" in logs_migration
    assert "alter table public.leads add column if not exists consent_basis text;" in schema
    assert "alter table public.leads add column if not exists approved_to_contact boolean not null default false;" in schema
    assert "create table if not exists public.jarvis_proactive_state" in schema
    assert "create table if not exists public.jarvis_memory" in schema
    assert "create table if not exists public.posts" in schema
    assert "id integer generated by default as identity primary key" in schema
    assert "key text not null unique" in schema
    assert "create table if not exists public.lead_company_aliases" in schema
    assert "create table if not exists public.lead_contact_candidates" in schema
    assert "create or replace function public.upsert_company_lead" in schema


def test_crm_tables_have_row_level_security_enabled():
    schema = (ROOT / "supabase" / "schema.sql").read_text(encoding="utf-8").lower()
    for table in ("leads", "logs", "tasks", "email_drafts", "jarvis_memory", "jarvis_proactive_state", "posts", "lead_company_aliases", "lead_contact_candidates"):
        assert f"alter table public.{table} enable row level security;" in schema


def test_lead_email_uniqueness_migration_has_non_destructive_preflight():
    migration = (
        ROOT / "supabase" / "migrations"
        / "20261125180000_unique_normalized_lead_email.sql"
    ).read_text(encoding="utf-8").lower()
    assert "lock table public.leads in share row exclusive mode" in migration
    assert "group by lower(btrim(email))" in migration
    assert "having count(*) > 1" in migration
    assert "resolve them manually" in migration
    assert "create unique index if not exists leads_email_normalized_uidx" in migration
    assert "delete from" not in migration
    assert "update public.leads" not in migration
    assert "insert into public.leads" not in migration


def test_schema_declares_normalized_lead_email_uniqueness():
    schema = (ROOT / "supabase" / "schema.sql").read_text(encoding="utf-8").lower()
    assert "create unique index if not exists leads_email_normalized_uidx" in schema
    assert "on public.leads (lower(btrim(email)))" in schema



